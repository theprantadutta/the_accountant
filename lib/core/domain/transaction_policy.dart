import 'package:the_accountant/data/datasources/local/app_database.dart'
    show Transaction;
import 'package:the_accountant/data/models/transaction.dart'
    show TransactionSpecialType, TransactionType;

/// The single, authoritative eligibility policy for every financial calculation
/// in the app.
///
/// Balance math, reports, budgets, category analytics, forecasts, and
/// credit/debt settlement all used to carry their own slightly different
/// filters, which is why the dashboard, the reports tab, and the stored wallet
/// balance could disagree about the same set of rows. Everything now routes
/// through these predicates instead, so there is exactly one definition of each
/// concept and changing it changes every consumer at once.
///
/// ## The four independent concepts
///
/// 1. **Cash realization** ([affectsWalletBalance]) — has the money actually
///    moved in or out of the wallet? A lend/borrow moves cash immediately, so it
///    is realized the moment it is recorded. An unpaid *upcoming* item has not
///    moved yet, so it is not.
/// 2. **Debt settlement** ([isSettled]) — has a receivable/payable been repaid
///    in full? This is derived from [Transaction.paidAmount] versus
///    [Transaction.amount] and is completely independent of concept 1. A brand
///    new loan is realized (cash moved) but *not* settled (nothing repaid).
///    Conflating these two was the "new loan shows as Settled" defect.
/// 3. **Analytics eligibility** ([countsAsIncome] / [countsAsExpense] /
///    [countsTowardCategorySpending]) — should the row appear in gross
///    earnings/spending? Realized *and* genuinely earned or spent: not an
///    internal wallet-to-wallet transfer, not a balance correction, and not a
///    loan or its repayment.
/// 4. **Forecast eligibility** ([isForecast]) — is this a not-yet-happened item
///    that belongs in upcoming/projection views only, never in realized totals?
class TransactionPolicy {
  const TransactionPolicy._();

  // ---------------------------------------------------------------------------
  // Classification
  // ---------------------------------------------------------------------------

  /// Value stored in [Transaction.transactionType] for the two legs of a
  /// wallet-to-wallet transfer.
  static String get regularType => TransactionType.regular.storageValue;

  static String get transferType => TransactionType.transfer.storageValue;

  /// Value stored in [Transaction.transactionType] for generated recurrence
  /// occurrences.
  static String get recurringInstanceType =>
      TransactionType.recurringInstance.storageValue;

  /// Value stored in [Transaction.transactionType] for a balance correction.
  static String get adjustmentType => TransactionType.adjustment.storageValue;

  /// How this row came to exist. Parsing goes through [TransactionType] so the
  /// column, the wire format, and this policy can never disagree about what a
  /// generated occurrence or a transfer leg looks like.
  static TransactionType kindOf(Transaction t) =>
      TransactionType.fromStorage(t.transactionType);

  /// Whether the row was generated by a recurrence schedule.
  static bool isRecurringInstance(Transaction t) =>
      kindOf(t) == TransactionType.recurringInstance;

  /// Whether the row is one leg of a wallet-to-wallet transfer.
  ///
  /// Transfers move money *between the user's own wallets*. Each leg legitimately
  /// changes its wallet's balance, but the pair is net-zero for the user, so a
  /// transfer must never be counted as income, expense, category spending,
  /// budget spending, or report earnings — otherwise every internal movement
  /// inflates gross income and gross expense by the same amount.
  static bool isTransfer(Transaction t) =>
      kindOf(t) == TransactionType.transfer;

  /// Whether the row is a balance correction.
  ///
  /// A correction records that the app's figure and the bank's disagreed, not
  /// that money was earned or spent. Counting it as either made a month of
  /// reconciling accounts read as overspending: the corrections landed in the
  /// budget alongside the purchases, and a large opening correction showed up
  /// as income nobody earned.
  static bool isAdjustment(Transaction t) =>
      kindOf(t) == TransactionType.adjustment;

  /// Whether the row repays (or reverses repayments of) a lend or borrow entry.
  ///
  /// Real money moving, so it changes the wallet — but being paid back is not
  /// earning, and paying a debt off is not spending.
  static bool isSettlement(Transaction t) => t.settlesTransactionId != null;

  /// Whether the row is a lend (`credit`) or borrow (`debt`) entry.
  static bool isCreditOrDebt(Transaction t) =>
      t.specialType == TransactionSpecialType.credit ||
      t.specialType == TransactionSpecialType.debt;

  /// Whether the row is a lend entry (someone owes the user money).
  static bool isCredit(Transaction t) =>
      t.specialType == TransactionSpecialType.credit;

  /// Whether the row is a borrow entry (the user owes someone money).
  static bool isDebt(Transaction t) =>
      t.specialType == TransactionSpecialType.debt;

  /// Whether the row is a not-yet-paid scheduled item.
  static bool isUpcoming(Transaction t) =>
      t.specialType == TransactionSpecialType.upcoming;

  /// Whether the row still exists (not soft-deleted).
  static bool isLive(Transaction t) => t.deletedAt == null;

  // ---------------------------------------------------------------------------
  // 1. Cash realization — the wallet-balance effect
  // ---------------------------------------------------------------------------

  /// Whether this transaction's cash has actually moved, and therefore whether
  /// it contributes to the wallet's running balance.
  ///
  /// This is the canonical balance predicate. [WalletBalanceService], the
  /// schema-11 migration backfill, transaction creation, transaction deletion,
  /// and every reporting figure derive from it, so a create and its matching
  /// delete can never disagree about whether a row counted.
  ///
  /// Credit/debt entries count regardless of [Transaction.isPaid] because the
  /// principal genuinely left (lend) or entered (borrow) the wallet when the
  /// loan was recorded; their repayment is tracked separately by
  /// [Transaction.paidAmount] and by the separate repayment transactions.
  static bool affectsWalletBalance(Transaction t) =>
      isRealized(live: isLive(t), isPaid: t.isPaid, specialType: t.specialType);

  /// [affectsWalletBalance] over plain fields, for models that are not a
  /// database row (the transaction list's view model). One definition, so a
  /// list total and a report can never disagree about which rows moved money.
  static bool isRealized({
    required bool live,
    required bool isPaid,
    required TransactionSpecialType? specialType,
  }) {
    if (!live) return false;
    return isPaid ||
        specialType == TransactionSpecialType.credit ||
        specialType == TransactionSpecialType.debt;
  }

  /// Whether [t] counts toward the goal it is linked to.
  ///
  /// Money has to have actually moved: a bill that has not been paid yet is not
  /// progress toward a holiday fund, and counting it would let a goal reach its
  /// target on transactions that never happened.
  ///
  /// Transfers **do** count here, which is the opposite of how budgets and
  /// reports treat them. Those ask what was earned and spent, and moving your
  /// own money between your own accounts is neither. A goal asks how much has
  /// been set aside, and moving money into savings is exactly how that is
  /// done — excluding transfers would leave the most common way of funding a
  /// goal invisible to it. Only the leg the user linked is counted, so the two
  /// halves of one transfer cannot both land on the same goal.
  static bool countsTowardObjective(Transaction t) => affectsWalletBalance(t);

  /// How much [t] moves an objective toward its target, in minor units.
  ///
  /// For a goal, every linked row that moved money is progress: a deposit to
  /// savings can be linked from either leg of its transfer, so direction says
  /// nothing about whether it was money set aside.
  ///
  /// A loan is different. It is a debt being paid off, so progress is money
  /// going out. The money borrowed is often linked to it too — it is the
  /// natural record of how the loan began — and counting it as progress made a
  /// loan read as paid off the moment it was taken out, and as more than 100%
  /// repaid after the first instalment.
  static int objectiveContribution(Transaction t, {required bool isLoan}) {
    if (!countsTowardObjective(t)) return 0;
    if (isLoan && t.isIncome) return 0;
    return t.amount.abs();
  }

  /// Signed effect of [t] on its wallet's balance, in integer minor units.
  ///
  /// Returns 0 when the transaction is not realized. Amounts are stored as
  /// magnitudes, so direction comes from [Transaction.isIncome] alone.
  static int walletBalanceEffect(Transaction t) {
    if (!affectsWalletBalance(t)) return 0;
    return t.isIncome ? t.amount.abs() : -t.amount.abs();
  }

  // ---------------------------------------------------------------------------
  // 2. Debt settlement — completely separate from cash realization
  // ---------------------------------------------------------------------------

  /// Whether a receivable/payable has been repaid in full.
  ///
  /// This is the ONLY settlement rule in the app. It is deliberately derived
  /// from amounts rather than from [Transaction.isPaid]: `isPaid` means "the
  /// cash movement happened", which is true for a brand new loan that has not
  /// been repaid at all. Labels, filters, unpaid tabs, the record-payment and
  /// settle actions, and overdue reminders all call this.
  ///
  /// A non-positive [Transaction.amount] is treated as settled so a zero-value
  /// row can never sit in the outstanding list forever.
  static bool isSettled(Transaction t) {
    if (t.amount <= 0) return true;
    return t.paidAmount >= t.amount;
  }

  /// The remaining unpaid principal of a receivable/payable, in minor units.
  ///
  /// Clamped at zero so an overpayment (paidAmount > amount) reads as fully
  /// settled rather than as a negative outstanding balance that would silently
  /// offset other loans in the exposure total.
  static int outstandingAmount(Transaction t) {
    final remaining = t.amount - t.paidAmount;
    return remaining > 0 ? remaining : 0;
  }

  /// Whether a credit/debt row is still owed (partially or entirely).
  static bool isOutstanding(Transaction t) => !isSettled(t);

  /// Whether a credit/debt row is past its due date and still owed.
  ///
  /// [now] is injectable so tests are not clock-dependent.
  static bool isOverdue(Transaction t, {DateTime? now}) {
    if (isSettled(t)) return false;
    final due = t.originalDueDate ?? t.date;
    return due.isBefore(now ?? DateTime.now());
  }

  /// Whether a partial (but not complete) repayment has been recorded.
  static bool hasPartialPayment(Transaction t) =>
      t.paidAmount > 0 && !isSettled(t);

  /// Repayment progress in the range 0.0–1.0, for progress bars.
  static double settlementProgress(Transaction t) {
    if (t.amount <= 0) return 1.0;
    final ratio = t.paidAmount / t.amount;
    return ratio.clamp(0.0, 1.0);
  }

  // ---------------------------------------------------------------------------
  // 3. Analytics eligibility — reports, dashboards, categories, budgets
  // ---------------------------------------------------------------------------

  /// Whether the row belongs in *any* earnings/spending analytic.
  ///
  /// Realized cash movement that was genuinely earned or spent.
  ///
  /// Loans are left out on both sides. Lending a
  /// friend money is not spending it, borrowing is not income, and neither is
  /// the money coming back: counted, one loan and its repayment inflated a
  /// month's spending and income by the same amount, and a large borrowing
  /// read as a windfall. The Credit & Debt screen is where loans are tracked.
  static bool countsInAnalytics(Transaction t) => countsInAnalyticsOf(
    live: isLive(t),
    isPaid: t.isPaid,
    specialType: t.specialType,
    kind: kindOf(t),
    settlesTransactionId: t.settlesTransactionId,
  );

  /// [countsInAnalytics] over plain fields; see [isRealized] for why.
  static bool countsInAnalyticsOf({
    required bool live,
    required bool isPaid,
    required TransactionSpecialType? specialType,
    required TransactionType kind,
    required String? settlesTransactionId,
  }) {
    if (!isRealized(live: live, isPaid: isPaid, specialType: specialType)) {
      return false;
    }
    if (specialType == TransactionSpecialType.credit ||
        specialType == TransactionSpecialType.debt ||
        settlesTransactionId != null) {
      return false;
    }
    return kind != TransactionType.transfer &&
        kind != TransactionType.adjustment;
  }

  /// Whether the row counts toward gross income / report earnings.
  static bool countsAsIncome(Transaction t) =>
      countsInAnalytics(t) && t.isIncome;

  /// Whether the row counts toward gross expense / report spending.
  static bool countsAsExpense(Transaction t) =>
      countsInAnalytics(t) && !t.isIncome;

  /// Whether the row counts toward per-category spending totals.
  ///
  /// Identical to [countsAsExpense] by design — category analytics and expense
  /// totals must never diverge. It exists as its own name so call sites read
  /// clearly and so a future divergence has to be made deliberately here.
  static bool countsTowardCategorySpending(Transaction t) => countsAsExpense(t);

  /// Whether the row counts toward a budget's consumed amount.
  ///
  /// A budget tracks either spending (`isIncome == false`) or earnings
  /// (`isIncome == true`); [budgetIsIncome] selects which side, and
  /// [budgetCategoryIds] optionally narrows it to a set of categories.
  ///
  /// The set exists because of subcategories. A budget names one category, but
  /// a budget is a limit on an area of spending rather than on a label: someone
  /// who sets a Food budget and then files lunches under Sandwich — a category
  /// they put inside Food — has not stopped spending on food. Matching the
  /// named id alone left that budget reading zero while the money went out, and
  /// a limit that silently never triggers is worse than no limit.
  ///
  /// This is deliberately the opposite of how reports treat the same rows,
  /// where Sandwich is its own line. The two answer different questions: "where
  /// did it go" wants the exact label, "have I overspent on food" wants the
  /// area. Callers build the set with [AppDatabase.categoryFamilyIds].
  static bool countsTowardBudget(
    Transaction t, {
    bool budgetIsIncome = false,
    Set<String>? budgetCategoryIds,
  }) {
    if (!countsInAnalytics(t)) return false;
    if (t.isIncome != budgetIsIncome) return false;
    if (budgetCategoryIds != null && budgetCategoryIds.isNotEmpty) {
      final categoryId = t.categoryId;
      if (categoryId == null || !budgetCategoryIds.contains(categoryId)) {
        return false;
      }
    }
    return true;
  }

  // ---------------------------------------------------------------------------
  // 4. Forecast eligibility
  // ---------------------------------------------------------------------------

  /// Whether the row is a pending scheduled item that belongs in forecast and
  /// upcoming views ONLY — never in realized reports or wallet balances.
  ///
  /// Skipped occurrences are excluded: the user has explicitly said this one
  /// will not happen.
  ///
  /// A subscription or repeating payment waiting to be confirmed is one too:
  /// its schedule asks before recording each payment, and until the user does
  /// it is expected money, not spent money.
  static bool isForecast(Transaction t) =>
      isLive(t) &&
      !t.isPaid &&
      !t.skipPaid &&
      (isUpcoming(t) ||
          t.specialType == TransactionSpecialType.subscription ||
          t.specialType == TransactionSpecialType.repetitive);

  /// Whether a forecast item is due in the future.
  static bool isFutureForecast(Transaction t, {DateTime? now}) =>
      isForecast(t) && t.date.isAfter(now ?? DateTime.now());

  /// Whether a forecast item is already past due.
  static bool isOverdueForecast(Transaction t, {DateTime? now}) =>
      isForecast(t) && !t.date.isAfter(now ?? DateTime.now());

  // ---------------------------------------------------------------------------
  // Aggregate helpers
  // ---------------------------------------------------------------------------

  /// Sum of realized income over [transactions], in minor units.
  static int totalIncome(Iterable<Transaction> transactions) => transactions
      .where(countsAsIncome)
      .fold<int>(0, (sum, t) => sum + t.amount.abs());

  /// Sum of realized expense over [transactions], in minor units.
  static int totalExpense(Iterable<Transaction> transactions) => transactions
      .where(countsAsExpense)
      .fold<int>(0, (sum, t) => sum + t.amount.abs());

  /// Total still owed across [transactions], in minor units.
  static int totalOutstanding(Iterable<Transaction> transactions) =>
      transactions
          .where(isLive)
          .fold<int>(0, (sum, t) => sum + outstandingAmount(t));

  /// Spending grouped by category id, in minor units. Rows without a category
  /// are grouped under [uncategorizedKey].
  static Map<String, int> spendingByCategory(
    Iterable<Transaction> transactions,
  ) {
    final result = <String, int>{};
    for (final t in transactions.where(countsTowardCategorySpending)) {
      final key = t.categoryId ?? uncategorizedKey;
      result[key] = (result[key] ?? 0) + t.amount.abs();
    }
    return result;
  }

  /// Grouping key used for transactions with no category assigned.
  static const String uncategorizedKey = 'uncategorized';
}
